@router.post("/log-analyzer")
async def log_analyzer(
    file: UploadFile = File(...),
):
    if not file.filename:
        raise HTTPException(
            status_code=400,
            detail="No log file was selected.",
        )

    temp_dir = OUTPUT_DIR / "uploads"
    temp_dir.mkdir(
        exist_ok=True
    )

    temp_file = (
        temp_dir
        / f"{uuid.uuid4()}_{file.filename}"
    )

    try:
        content = await file.read()

        temp_file.write_bytes(
            content
        )

        (
            info_count,
            warning_count,
            error_count,
            errors,
        ) = analyze_log_file(
            str(temp_file)
        )

        return {
            "filename": file.filename,
            "info_count": info_count,
            "warning_count": warning_count,
            "error_count": error_count,
            "errors": make_json_safe(
                errors
            ),
        }

    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail={
                "message": (
                    "Log analysis failed."
                ),
                "filename": file.filename,
                "error_type": type(exc).__name__,
                "reason": str(exc),
            },
        )

    finally:
        if temp_file.exists():
            temp_file.unlink()


