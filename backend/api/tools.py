@router.post("/reports/health")
def health_report(
    output_format: str = Query(
        "text",
        pattern="^(json|csv|html|text)$",
    ),
):
    try:
        health = get_system_health()

        statuses = {
            "cpu": determine_status(
                health["cpu_usage"]
            ),
            "memory": determine_status(
                health["memory_usage"]
            ),
            "disk": determine_status(
                health["disk_usage"]
            ),
        }

        result = generate_report(
            health,
            statuses,
            output_format=output_format,
        )

        report_file = find_generated_file(
            result,
            REPORTS_DIR,
            extensions=(
                ".json",
                ".csv",
                ".html",
                ".txt",
            ),
        )

        if report_file is None:
            raise FileNotFoundError(
                "The report generator did not "
                "create a report file."
            )

        return {
            "success": True,
            "format": output_format,
            "filename": report_file.name,
            "path": str(report_file),
            "download_url": (
                f"/api/reports/download/"
                f"{report_file.name}"
            ),
        }

    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail={
                "message": (
                    "Report generation failed."
                ),
                "format": output_format,
                "error_type": type(exc).__name__,
                "reason": str(exc),
            },
        )


