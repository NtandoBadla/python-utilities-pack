class FileOrganizerRequest(BaseModel):
    folder_path: str


@router.post("/file-organizer")
def file_organizer(
    request: FileOrganizerRequest,
):
    folder = Path(
        request.folder_path
    ).expanduser()

    if not folder.exists():
        raise HTTPException(
            status_code=400,
            detail={
                "message": (
                    "The selected folder does not exist."
                ),
                "folder": str(folder),
                "reason": (
                    "The path could not be found "
                    "on this computer."
                ),
            },
        )

    if not folder.is_dir():
        raise HTTPException(
            status_code=400,
            detail={
                "message": (
                    "The selected path is not a folder."
                ),
                "folder": str(folder),
                "reason": (
                    "Please provide a directory "
                    "rather than a file."
                ),
            },
        )

    try:
        result = organize_files(
            str(folder)
        )

        if isinstance(result, dict):
            return {
                "success": (
                    len(
                        result.get(
                            "errors",
                            [],
                        )
                    )
                    == 0
                ),
                "folder": str(folder),
                "moved": make_json_safe(
                    result.get(
                        "moved",
                        [],
                    )
                ),
                "skipped": make_json_safe(
                    result.get(
                        "skipped",
                        [],
                    )
                ),
                "errors": make_json_safe(
                    result.get(
                        "errors",
                        [],
                    )
                ),
                "summary": {
                    "moved": len(
                        result.get(
                            "moved",
                            [],
                        )
                    ),
                    "skipped": len(
                        result.get(
                            "skipped",
                            [],
                        )
                    ),
                    "errors": len(
                        result.get(
                            "errors",
                            [],
                        )
                    ),
                },
            }

        return {
            "success": True,
            "folder": str(folder),
            "message": (
                "File organization completed "
                "successfully."
            ),
            "result": make_json_safe(
                result
            ),
            "summary": {
                "moved": "Completed",
                "skipped": 0,
                "errors": 0,
            },
        }

    except PermissionError as exc:
        raise HTTPException(
            status_code=403,
            detail={
                "message": (
                    "Permission denied while "
                    "organizing files."
                ),
                "folder": str(folder),
                "reason": str(exc),
                "suggestion": (
                    "Make sure the folder is not "
                    "protected and that you have "
                    "permission to move files."
                ),
            },
        )

    except FileNotFoundError as exc:
        raise HTTPException(
            status_code=404,
            detail={
                "message": (
                    "A file or folder could not "
                    "be found."
                ),
                "folder": str(folder),
                "reason": str(exc),
            },
        )

    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail={
                "message": (
                    "File organization failed."
                ),
                "folder": str(folder),
                "error_type": type(exc).__name__,
                "reason": str(exc),
            },
        )


