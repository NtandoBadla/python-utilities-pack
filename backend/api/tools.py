@router.post("/csv-validator")
async def csv_validator(
    file: UploadFile = File(...),
):
    if not file.filename:
        raise HTTPException(
            status_code=400,
            detail="No CSV file was selected.",
        )

    if not file.filename.lower().endswith(
        ".csv"
    ):
        raise HTTPException(
            status_code=400,
            detail={
                "message": "Invalid file type.",
                "reason": (
                    "Please upload a CSV file."
                ),
            },
        )

    upload_dir = (
        OUTPUT_DIR / "csv_uploads"
    )

    upload_dir.mkdir(
        exist_ok=True
    )

    cleaned_dir = (
        OUTPUT_DIR / "cleaned_csv"
    )

    cleaned_dir.mkdir(
        exist_ok=True
    )

    unique_id = uuid.uuid4().hex

    input_path = (
        upload_dir
        / f"{unique_id}_{file.filename}"
    )

    cleaned_filename = (
        f"cleaned_"
        f"{Path(file.filename).stem}_"
        f"{unique_id[:8]}.csv"
    )

    output_path = (
        cleaned_dir
        / cleaned_filename
    )

    try:
        # ----------------------------------------------------
        # Save uploaded CSV
        # ----------------------------------------------------

        content = await file.read()

        input_path.write_bytes(
            content
        )

        # ----------------------------------------------------
        # Run the existing Python validator
        # ----------------------------------------------------

        result = process_csv(
            str(input_path),
            output_path=str(output_path),
        )

        # ----------------------------------------------------
        # Normalise validator result
        # ----------------------------------------------------

        clean_records = []
        invalid_records = []
        duplicate_records = []

        returned_output_path = output_path

        if isinstance(result, tuple):

            if len(result) >= 1:
                clean_records = result[0]

            if len(result) >= 2:
                invalid_records = result[1]

            if len(result) >= 3:
                duplicate_records = result[2]

            if (
                len(result) >= 4
                and result[3]
            ):
                returned_output_path = Path(
                    str(result[3])
                )

                if not returned_output_path.is_absolute():
                    returned_output_path = (
                        PROJECT_ROOT
                        / returned_output_path
                    )

        elif isinstance(result, dict):

            clean_records = result.get(
                "clean",
                result.get(
                    "clean_records",
                    [],
                ),
            )

            invalid_records = result.get(
                "invalid",
                result.get(
                    "invalid_records",
                    [],
                ),
            )

            duplicate_records = result.get(
                "duplicates",
                result.get(
                    "duplicate_records",
                    [],
                ),
            )

            returned_output_path = Path(
                str(
                    result.get(
                        "output_path",
                        output_path,
                    )
                )
            )

            if not returned_output_path.is_absolute():
                returned_output_path = (
                    PROJECT_ROOT
                    / returned_output_path
                )

        # ----------------------------------------------------
        # Guarantee lists
        # ----------------------------------------------------

        if not isinstance(
            clean_records,
            list,
        ):
            clean_records = list(
                clean_records or []
            )

        if not isinstance(
            invalid_records,
            list,
        ):
            invalid_records = list(
                invalid_records or []
            )

        if not isinstance(
            duplicate_records,
            list,
        ):
            duplicate_records = list(
                duplicate_records or []
            )

        # ----------------------------------------------------
        # Make sure cleaned CSV exists
        # ----------------------------------------------------

        if not returned_output_path.exists():

            if output_path.exists():
                returned_output_path = (
                    output_path
                )

            else:
                raise FileNotFoundError(
                    "The CSV validator completed "
                    "but did not create the "
                    "cleaned CSV file."
                )

        # ----------------------------------------------------
        # Copy cleaned CSV into controlled
        # download directory
        # ----------------------------------------------------

        if (
            returned_output_path.resolve()
            != output_path.resolve()
        ):
            output_path.write_bytes(
                returned_output_path.read_bytes()
            )

        # ----------------------------------------------------
        # Download URL
        # ----------------------------------------------------

        download_url = (
            f"/api/csv-validator/download/"
            f"{output_path.name}"
        )

        # ----------------------------------------------------
        # Normalize invalid records
        # ----------------------------------------------------

        invalid_response = (
            normalize_invalid_records(
                invalid_records
            )
        )

        # ----------------------------------------------------
        # Counts
        # ----------------------------------------------------

        clean_count = len(
            clean_records
        )

        invalid_count = len(
            invalid_records
        )

        duplicate_count = len(
            duplicate_records
        )

        # ----------------------------------------------------
        # API RESPONSE
        # ----------------------------------------------------

        return {
            "success": True,
            "filename": file.filename,

            # Full record arrays
            "clean": make_json_safe(
                clean_records
            ),

            "invalid": invalid_response,

            "duplicates": make_json_safe(
                duplicate_records
            ),

            # Numeric counts
            "clean_records": clean_count,
            "invalid_records": invalid_count,
            "duplicate_records": duplicate_count,

            # Summary
            "counts": {
                "clean": clean_count,
                "invalid": invalid_count,
                "duplicates": duplicate_count,
                "total": (
                    clean_count
                    + invalid_count
                    + duplicate_count
                ),
            },

            # Cleaned file
            "cleaned_file": (
                output_path.name
            ),

            "output_path": str(
                output_path
            ),

            # Download
            "download_url": download_url,
        }

    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail={
                "message": (
                    "CSV validation failed."
                ),
                "filename": file.filename,
                "error_type": type(exc).__name__,
                "reason": str(exc),
            },
        )

    finally:
        if input_path.exists():
            input_path.unlink()


