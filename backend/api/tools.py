def make_json_safe(value: Any):
    """
    Convert values returned by Python scripts into JSON-safe data.
    """
    if value is None:
        return None

    if isinstance(value, (str, int, float, bool)):
        return value

    if isinstance(value, Path):
        return str(value)

    if isinstance(value, dict):
        return {
            str(key): make_json_safe(val)
            for key, val in value.items()
        }

    if isinstance(value, (list, tuple, set)):
        return [
            make_json_safe(item)
            for item in value
        ]

    return str(value)


def normalize_invalid_records(records):
    """
    Convert invalid CSV validation results into a consistent
    frontend-friendly structure.

    The data validator returns invalid records as:

        (
            record,
            ["Missing 'email'"]
        )

    The API returns them as:

        {
            "record": {...},
            "problems": ["Missing 'email'"]
        }
    """
    normalized = []

    for item in records:

        if isinstance(item, dict):
            record = item.get(
                "record",
                {},
            )

            problems = item.get(
                "problems",
                [],
            )

        elif isinstance(item, (tuple, list)) and len(item) >= 2:
            record = item[0]
            problems = item[1]

        else:
            record = {}
            problems = [str(item)]

        normalized.append(
            {
                "record": make_json_safe(record),
                "problems": make_json_safe(problems),
            }
        )

    return normalized


def find_generated_file(
    result: Any,
    directory: Path,
    extensions: tuple[str, ...] = (),
):
    """
    Try to determine which file was generated by a script.
    """

    if isinstance(result, (str, Path)):
        candidate = Path(result)

        if not candidate.is_absolute():
            candidate = PROJECT_ROOT / candidate

        if candidate.exists() and candidate.is_file():
            return candidate

    if isinstance(result, dict):
        for key in (
            "output_path",
            "path",
            "file",
            "filename",
        ):
            value = result.get(key)

            if value:
                candidate = Path(str(value))

                if not candidate.is_absolute():
                    candidate = PROJECT_ROOT / candidate

                if candidate.exists() and candidate.is_file():
                    return candidate

    files = [
        path
        for path in directory.iterdir()
        if path.is_file()
        and (
            not extensions
            or path.suffix.lower() in extensions
        )
    ]

    if not files:
        return None

    return max(
        files,
        key=lambda path: path.stat().st_mtime,
    )


